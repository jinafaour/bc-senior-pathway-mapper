st.write("1. **British Columbia Ministry of Education:** Graduation Requirements and Course Whitelists (Dogwood Diploma framework).")
st.write("2. **University of British Columbia (UBC):** Undergraduate Admissions Prerequisite Schedules for Applied Science, Science, and Sauder School of Business.")
st.write("3. **Simon Fraser University (SFU):** Faculty of Applied Sciences and Beedie School of Business Course Requirements.")
